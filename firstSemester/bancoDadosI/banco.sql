    CONSTRAINT PK_TB_PR_LIBERADA_LIBERADORA PRIMARY KEY(COD_DISCIPLINA_LIBERADA, COD_DISCIPLINA_LIBERADORA),
    CONSTRAINT FK_TB_PR_LIBERADA FOREIGN KEY(COD_DISCIPLINA_LIBERADA) REFERENCES TB_DISCIPLINA(COD_DISCIPLINA),
    CONSTRAINT FK_TB_PR_LIBERADORA FOREIGN KEY(COD_DISCIPLINA_LIBERADORA) REFERENCES TB_DISCIPLINA(COD_DISCIPLINA)
