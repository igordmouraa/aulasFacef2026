CREATE TABLE TB_ALUNO(
    COD_ALUNO INTEGER,
    NM_ALUNO VARCHAR(40),
    COD_CURSO INTEGER CONSTRAINT NN_TB_ALUNO_COD_CURSO NOT NULL,
    DT_NASCIMENTO DATE,
    CONSTRAINT PK_TB_ALUNO_COD_ALUNO PRIMARY KEY(COD_ALUNO),
