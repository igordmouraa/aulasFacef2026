CREATE TABLE TB_DISCIPLINA(
    COD_DISCIPLINA INTEGER,
    COD_DEPTO      INTEGER CONSTRAINT NN_DISC_COD_DEPTO NOT NULL, 
    NM_DISCIPLINA  VARCHAR(40),
